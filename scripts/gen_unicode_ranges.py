"""Generate src/unicode_ranges.inc - codepoint range tables for the Qwen2
pre-tokenizer regex classes (\\p{L}, \\p{N}, \\s).

The Rust `regex` crate used by HF tokenizers resolves:
  \\p{L} -> General_Category L*        (Lu, Ll, Lt, Lm, Lo)
  \\p{N} -> General_Category N*        (Nd, Nl, No)
  \\s    -> Unicode White_Space property

Usage: python scripts/gen_unicode_ranges.py
"""
import sys
import unicodedata

OUT = "src/core/text/unicode_ranges.inc"
MAX_CP = 0x110000


def ranges_for(pred):
    rs = []
    start = None
    for cp in range(MAX_CP):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            rs.append((start, cp - 1))
            start = None
    if start is not None:
        rs.append((start, MAX_CP - 1))
    return rs


def is_L(cp):
    return unicodedata.category(chr(cp)).startswith("L")


def is_N(cp):
    return unicodedata.category(chr(cp)).startswith("N")


# Unicode White_Space property (PropList.txt)
WHITE_SPACE = [
    (0x0009, 0x000D), (0x0020, 0x0020), (0x0085, 0x0085), (0x00A0, 0x00A0),
    (0x1680, 0x1680), (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F),
    (0x205F, 0x205F), (0x3000, 0x3000),
]


def emit(f, name, rs):
    f.write(f"static const uint32_t {name}[][2] = {{\n")
    for i in range(0, len(rs), 6):
        chunk = ", ".join(f"{{0x{a:X},0x{b:X}}}" for a, b in rs[i:i + 6])
        f.write(f"    {chunk},\n")
    f.write("};\n")
    f.write(f"static const int {name}_N = {len(rs)};\n\n")


def main():
    rs_l = ranges_for(is_L)
    rs_n = ranges_for(is_N)
    print(f"L ranges: {len(rs_l)}, N ranges: {len(rs_n)}, space ranges: {len(WHITE_SPACE)}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/gen_unicode_ranges.py - do not edit.\n")
        f.write("// Sorted [first,last] codepoint ranges for \\p{L}, \\p{N} and Unicode White_Space.\n\n")
        emit(f, "vc3_uni_L", rs_l)
        emit(f, "vc3_uni_N", rs_n)
        emit(f, "vc3_uni_S", WHITE_SPACE)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
