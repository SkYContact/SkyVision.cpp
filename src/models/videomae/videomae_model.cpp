// videomae_model.cpp - VideoMAE video encoder backend.
//
// One self-contained GGUF (arch `videomae`), converted from any transformers
// `videomae` checkpoint (MCG-NJU/videomae-base and its fine-tunes). It is a
// pure video tower - no tokenizer, no KV cache, no decoding: one forward pass
// over num_frames//tubelet * (H/patch) * (W/patch) tokens produces either a
// Kinetics-style label distribution (when the checkpoint carries a classifier)
// or the pooled embedding.
//
// Forward, matching transformers.models.videomae exactly:
//   patch_embed: Conv3d(C, dim, k=(tubelet, patch, patch)) folded into a matmul
//     over tokens ordered (t', h', w') with elements (c, dt, dh, dw)
//   + fixed sin-cos position table (generated by the converter, never learned)
//   NO cls token - the "pooled" vector is token 0 unless use_mean_pooling
//   12 pre-norm blocks: LN -> full (non-causal) attention with q/v bias and no
//     k bias -> LN -> MLP with GELU(erf)
//   final LayerNorm, then classifier(pooled) for fine-tunes
//
// The whole clip fits in one graph (1568 tokens for the base model), so
// attention is a single unmasked flash_attn_ext per layer.
//
// The clip shape never changes, so the graph is built ONCE in load() and then
// replayed: a stable ggml_cgraph is what lets ggml capture a CUDA graph
// (capture key = nodes[0], it must not be rebuilt per call), and on CPU it
// skips the per-clip graph build + allocator pass. Only the input tensor is
// re-filled between clips.
//
// The block body is core/vit_block.hpp, shared with the moondream and
// VideoChat3 towers (same LN -> qkv -> attention -> wo -> LN -> MLP sequence);
// the only difference is the activation, VideoMAE's nn.GELU() is the exact erf
// form, so it passes a gelu hook instead of writing a second block.
